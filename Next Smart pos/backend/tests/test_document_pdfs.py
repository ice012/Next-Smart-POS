def test_the_receipt_still_works_after_adding_the_invoice(client, owner):
    """The two documents must not interfere with each other."""
    sale = _create_sale(client, owner["headers"])

    receipt = client.get(f"/api/sales/{sale['id']}/receipt", headers=owner["headers"])
    invoice = client.get(f"/api/sales/{sale['id']}/invoice", headers=owner["headers"])

    assert receipt.status_code == 200
    assert invoice.status_code == 200
    # 80mm roll versus A4 sheet.
    assert "SALES RECEIPT" in pdf_text(receipt.data)
    assert "TAX INVOICE" in pdf_text(invoice.data)
