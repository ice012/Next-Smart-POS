"""A4 PDF documents: quotations and tax invoices.

Both are generated by PDFService and served from a GET route, so these tests
cover the rendered content as well as the access rules around it.
"""
from conftest import auth_headers, register_business  # noqa: F401

from pdf_text import pdf_text

SA_HEADERS = {
    "X-SuperAdmin-Token": "test-superadmin-token",
    **auth_headers("unused"),
}
SA_HEADERS.pop("Authorization")


def _enable_enterprise(client, owner):
    plans = client.get("/api/superadmin/plans", headers=SA_HEADERS)
    assert plans.status_code == 200, plans.get_json()
    plan_ids = {p["code"]: p["id"] for p in plans.get_json()["data"]["plans"]}
    changed = client.post(
        f"/api/superadmin/businesses/{owner['business_id']}/plan",
        headers=SA_HEADERS,
        json={"plan_id": plan_ids["enterprise"]},
    )
    assert changed.status_code == 200, changed.get_json()


def _create_item(client, headers, **overrides):
    body = {
        "type": "product",
        "name": "Widget",
        "cost_price": 20,
        "selling_price": 50,
        "is_inventory_tracked": False,
    }
    body.update(overrides)
    response = client.post("/api/items", headers=headers, json=body)
    assert response.status_code == 201, response.get_json()
    return response.get_json()["data"]["item"]


def _create_customer(client, headers, **overrides):
    body = {"display_name": "Acme Buyer"}
    body.update(overrides)
    response = client.post("/api/customers", headers=headers, json=body)
    assert response.status_code == 201, response.get_json()
    return response.get_json()["data"]["customer"]


def _create_tax(client, headers, rate=0):
    response = client.post("/api/finance/tax-configs", headers=headers, json={
        "name": f"VAT {rate}",
        "code": f"VAT{rate}",
        "rate": rate,
        "applies_to": "sales",
        "is_default": True,
    })
    assert response.status_code == 201, response.get_json()


def _create_quotation(client, headers, **overrides):
    body = {"items": [{"item_id": _create_item(client, headers)["id"], "quantity": 2}]}
    body.update(overrides)
    response = client.post("/api/quotations", headers=headers, json=body)
    assert response.status_code == 201, response.get_json()
    return response.get_json()["data"]["quotation"]


def _create_sale(client, headers, **overrides):
    body = {
        "sale_type": "cash",
        "items": [{"item_id": _create_item(client, headers)["id"], "quantity": 2}],
        "payments": [{"payment_method": "cash", "amount": 100}],
    }
    body.update(overrides)
    response = client.post("/api/sales", headers=headers, json=body)
    assert response.status_code == 201, response.get_json()
    return response.get_json()["data"]["sale"]


# --- quotation PDF ----------------------------------------------------------

def test_quotation_pdf_is_served(client, owner):
    _enable_enterprise(client, owner)
    _create_tax(client, owner["headers"])
    quotation = _create_quotation(client, owner["headers"])

    response = client.get(f"/api/quotations/{quotation['id']}/pdf", headers=owner["headers"])

    assert response.status_code == 200, response.get_json()
    assert response.mimetype == "application/pdf"
    assert response.data.startswith(b"%PDF")
    assert f"quotation-{quotation['quotation_number']}.pdf".encode() in response.headers["Content-Disposition"].encode()


def test_quotation_pdf_renders_the_document(client, owner):
    _enable_enterprise(client, owner)
    _create_tax(client, owner["headers"])
    customer = _create_customer(client, owner["headers"])
    quotation = _create_quotation(client, owner["headers"], customer_id=customer["id"])

    data = client.get(
        f"/api/quotations/{quotation['id']}/pdf", headers=owner["headers"]
    ).data
    text = pdf_text(data)

    assert "QUOTATION" in text
    assert quotation["quotation_number"] in text
    assert "Test Retail Ltd" in text
    assert "Acme Buyer" in text
    assert "Widget" in text
    assert "TOTAL" in text
    # GBP, the currency the owner registered with.
    assert "100.00" in text
    assert "\u00a3" in text or "GBP" in text


def test_quotation_pdf_includes_notes_and_status(client, owner):
    _enable_enterprise(client, owner)
    _create_tax(client, owner["headers"])
    quotation = _create_quotation(client, owner["headers"], notes="Delivery in 3 weeks")

    text = pdf_text(client.get(
        f"/api/quotations/{quotation['id']}/pdf", headers=owner["headers"]
    ).data)

    assert "Delivery in 3 weeks" in text
    assert "Draft" in text
    assert "Valid until" in text


